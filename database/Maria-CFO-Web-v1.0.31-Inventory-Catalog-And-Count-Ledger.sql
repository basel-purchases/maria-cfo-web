CREATE TABLE IF NOT EXISTS public.v131_count_batches (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 source_sha256 text NOT NULL,
 source_filename text NOT NULL DEFAULT 'Excel',
 count_date date NOT NULL,
 submitted_at timestamptz NOT NULL DEFAULT now(),
 last_submitted_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(source_sha256,count_date)
);
CREATE TABLE IF NOT EXISTS public.v131_count_batch_lines (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 batch_id uuid NOT NULL REFERENCES public.v131_count_batches(id) ON DELETE RESTRICT,
 material_id uuid NOT NULL REFERENCES public.materials(id) ON DELETE RESTRICT,
 count_id uuid NOT NULL REFERENCES public.v126_physical_counts(id) ON DELETE RESTRICT,
 original_name text NOT NULL,
 source_department text,
 source_unit text NOT NULL,
 source_quantity numeric(20,6) NOT NULL,
 operation text NOT NULL CHECK(operation IN ('recorded','already_counted')),
 UNIQUE(batch_id,material_id)
);
CREATE INDEX IF NOT EXISTS v131_count_batch_lines_count_idx ON public.v131_count_batch_lines(count_id);
ALTER TABLE public.v131_count_batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.v131_count_batch_lines ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS v131_owner_read_batches ON public.v131_count_batches;
