-- Apply only to existing, unclassified materials. Unknown material names are never fabricated from empty count rows.
-- Running this repeatedly is safe: category already set => no change.
CREATE OR REPLACE FUNCTION public.v131_classify_count_catalog(p_rows jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $class$
DECLARE v_row jsonb;v_name text;v_dept text;v_id uuid;v_cat uuid;
 v_matches int;v_added int:=0;v_already int:=0;v_unknown int:=0;v_new_categories int:=0;
BEGIN
 IF NOT public.is_app_owner() THEN RAISE EXCEPTION 'Access denied'; END IF;
 IF jsonb_typeof(p_rows)<>'array' OR jsonb_array_length(p_rows)>150
 THEN RAISE EXCEPTION 'V131_CATALOG_MAX_150_ITEMS'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('maria-v131-count-categories',0));
 FOR v_row IN SELECT value FROM jsonb_array_elements(p_rows) LOOP
  v_name:=regexp_replace(btrim(coalesce(v_row->>'name','')), '[[:space:]]+',' ','g');
  v_dept:=regexp_replace(btrim(coalesce(v_row->>'department','')), '[[:space:]]+',' ','g');
  IF length(v_name) NOT BETWEEN 1 AND 250 OR length(v_dept) NOT BETWEEN 1 AND 120
  THEN RAISE EXCEPTION 'V131_COUNT_CATEGORY_INVALID'; END IF;
  SELECT count(*),min(id::text)::uuid INTO v_matches,v_id FROM public.materials
   WHERE public.recipe_key_normalize_v027(name)=public.recipe_key_normalize_v027(v_name);
  IF v_matches>1 THEN RAISE EXCEPTION 'V131_AMBIGUOUS_CATEGORY_MATERIAL: %',v_name; END IF;
  IF v_id IS NULL THEN v_unknown:=v_unknown+1;CONTINUE;END IF;
  PERFORM 1 FROM public.materials WHERE id=v_id FOR UPDATE;
  IF EXISTS(SELECT 1 FROM public.materials WHERE id=v_id AND category_id_v023 IS NOT NULL) THEN
   v_already:=v_already+1;CONTINUE;
  END IF;
  SELECT id INTO v_cat FROM public.material_categories_v023 WHERE lower(btrim(name))=lower(v_dept) LIMIT 1;
  IF v_cat IS NULL THEN
   INSERT INTO public.material_categories_v023(name) VALUES(v_dept)
    ON CONFLICT DO NOTHING RETURNING id INTO v_cat;
   IF v_cat IS NOT NULL THEN v_new_categories:=v_new_categories+1;
   ELSE SELECT id INTO v_cat FROM public.material_categories_v023 WHERE lower(btrim(name))=lower(v_dept) LIMIT 1;
   END IF;
  END IF;
  IF v_cat IS NULL THEN RAISE EXCEPTION 'V131_CATEGORY_CREATION_FAILED';END IF;
  UPDATE public.materials SET category_id_v023=v_cat WHERE id=v_id AND category_id_v023 IS NULL;
  IF FOUND THEN v_added:=v_added+1;END IF;
 END LOOP;
 RETURN jsonb_build_object('classified',v_added,'alreadyClassified',v_already,
  'unknownMaterialNames',v_unknown,'newCategories',v_new_categories);
END;
$class$;
REVOKE ALL ON FUNCTION public.v131_classify_count_catalog(jsonb) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.v131_classify_count_catalog(jsonb) TO authenticated;

-- Inventory count idempotency is per (actual material, count date), not per file hash.
-- Re-uploading a modified workbook cannot overwrite an approved dated count; it only records missing materials.
CREATE OR REPLACE FUNCTION public.v131_import_physical_counts(
 p_sha256 text,p_records jsonb,p_create_missing boolean DEFAULT false,p_filename text DEFAULT 'Excel')
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $count$
DECLARE v_row jsonb;v_existing uuid;v_mat uuid;v_key text;v_new jsonb:='[]'::jsonb;
 v_new_result jsonb:='{}'::jsonb;v_batch uuid;v_date date;v_name text;v_total int:=0;
 v_skipped int:=0;v_new_count int:=0;v_count_id uuid;v_operation text;v_name_matches int;
 v_new_keys text[]:=ARRAY[]::text[];
BEGIN
 IF NOT public.is_app_owner() THEN RAISE EXCEPTION 'Access denied';END IF;
 IF p_sha256 !~ '^[0-9a-f]{64}$' OR jsonb_typeof(p_records)<>'array'
  OR jsonb_array_length(p_records) NOT BETWEEN 1 AND 150
  OR length(coalesce(p_filename,'')) NOT BETWEEN 1 AND 250
 THEN RAISE EXCEPTION 'V131_COUNT_INVALID_IMPORT'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('maria-v126-physical-count',0));
 FOR v_row IN SELECT value FROM jsonb_array_elements(p_records) LOOP
  v_name:=btrim(coalesce(v_row->>'name',''));
  IF length(v_name) NOT BETWEEN 1 AND 250 OR coalesce(v_row->>'date','') !~ '^20[0-9]{2}-[01][0-9]-[0-3][0-9]$'
  THEN RAISE EXCEPTION 'V131_COUNT_ROW_NAME_OR_DATE_INVALID'; END IF;
  v_date:=(v_row->>'date')::date;
  SELECT count(*),min(id::text)::uuid INTO v_name_matches,v_mat FROM public.materials
   WHERE public.recipe_key_normalize_v027(name)=public.recipe_key_normalize_v027(v_name);
  IF v_name_matches>1 THEN RAISE EXCEPTION 'V131_AMBIGUOUS_COUNT_MATERIAL: %',v_name; END IF;
  v_existing:=NULL;
  IF v_mat IS NOT NULL THEN
   SELECT id INTO v_existing FROM public.v126_physical_counts WHERE material_id=v_mat AND count_date=v_date;
  END IF;
  IF v_existing IS NOT NULL THEN v_skipped:=v_skipped+1;
  ELSE
    v_new:=v_new||jsonb_build_array(v_row);
    v_new_keys:=array_append(v_new_keys,public.recipe_key_normalize_v027(v_name)||'|'||v_date::text);
  END IF;
  v_total:=v_total+1;
 END LOOP;
 IF jsonb_array_length(v_new)>0 THEN
  v_new_result:=public.v126_import_physical_counts(p_sha256,v_new,p_create_missing);
  v_new_count:=coalesce((v_new_result->>'approved')::integer,0);
 END IF;
 FOR v_row IN SELECT value FROM jsonb_array_elements(p_records) LOOP
  v_name:=btrim(v_row->>'name');v_date:=(v_row->>'date')::date;
  SELECT id INTO v_mat FROM public.materials
   WHERE public.recipe_key_normalize_v027(name)=public.recipe_key_normalize_v027(v_name) LIMIT 1;
  SELECT id INTO v_count_id FROM public.v126_physical_counts WHERE material_id=v_mat AND count_date=v_date;
  IF v_count_id IS NULL THEN RAISE EXCEPTION 'V131_COUNT_NOT_RECORDED: %',v_name;END IF;
  INSERT INTO public.v131_count_batches(source_sha256,source_filename,count_date)
    VALUES(p_sha256,p_filename,v_date)
    ON CONFLICT(source_sha256,count_date) DO UPDATE SET last_submitted_at=now(),source_filename=excluded.source_filename
    RETURNING id INTO v_batch;
  -- 'already_counted' means the count existed before THIS upload, not a replacement.
  v_operation:=CASE WHEN (public.recipe_key_normalize_v027(v_name)||'|'||v_date::text)=ANY(v_new_keys)
                   THEN 'recorded' ELSE 'already_counted' END;
  INSERT INTO public.v131_count_batch_lines(batch_id,material_id,count_id,original_name,
     source_department,source_unit,source_quantity,operation)
  VALUES(v_batch,v_mat,v_count_id,v_name,left(coalesce(v_row->>'department',''),140),
    btrim(v_row->>'unit'),(v_row->>'quantity')::numeric,v_operation)
  ON CONFLICT(batch_id,material_id) DO NOTHING;
 END LOOP;
 RETURN jsonb_build_object('approved',v_new_count,'alreadyApproved',v_skipped,
  'newCatalogMaterials',coalesce((v_new_result->>'newCatalogMaterials')::int,0),
  'noChange',coalesce((v_new_result->>'noChange')::int,0),'rowsReceived',v_total);
END;
$count$;
REVOKE ALL ON FUNCTION public.v131_import_physical_counts(text,jsonb,boolean,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.v131_import_physical_counts(text,jsonb,boolean,text) TO authenticated;

CREATE OR REPLACE FUNCTION public.v131_counts_history()
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $history$
 SELECT coalesce(jsonb_agg(jsonb_build_object('id',b.id,'date',b.count_date,
 'file',b.source_filename,'submittedAt',b.submitted_at,'lastSubmittedAt',b.last_submitted_at,
 'rows',(SELECT count(*) FROM public.v131_count_batch_lines l WHERE l.batch_id=b.id),
 'posted',(SELECT count(*) FROM public.v131_count_batch_lines l WHERE l.batch_id=b.id AND l.operation='recorded'),
 'duplicates',(SELECT count(*) FROM public.v131_count_batch_lines l WHERE l.batch_id=b.id AND l.operation='already_counted')
 ) ORDER BY b.count_date DESC,b.submitted_at DESC),'[]'::jsonb)
 FROM public.v131_count_batches b WHERE public.is_app_owner();
$history$;
REVOKE ALL ON FUNCTION public.v131_counts_history() FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.v131_counts_history() TO authenticated;

CREATE OR REPLACE FUNCTION public.v131_count_history_detail(p_batch_id uuid)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $details$
 SELECT coalesce(jsonb_agg(jsonb_build_object('name',l.original_name,
   'category',l.source_department,'quantity',l.source_quantity,'unit',l.source_unit,
   'date',c.count_date,'difference',c.adjustment_delta_base,'countedBase',c.counted_base,
   'stockAfter',c.resulting_current_base,'movementId',c.adjustment_movement_id,
   'state',l.operation) ORDER BY l.original_name),'[]'::jsonb)
 FROM public.v131_count_batch_lines l JOIN public.v126_physical_counts c ON c.id=l.count_id
 WHERE l.batch_id=p_batch_id AND public.is_app_owner();
$details$;
REVOKE ALL ON FUNCTION public.v131_count_history_detail(uuid) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.v131_count_history_detail(uuid) TO authenticated;
